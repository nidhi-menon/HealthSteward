"""Builds 3 review-packet .md/.pdf files (one per round of eval/
build_review_assignments.py's 30-case split) from the outputs already
generated by eval/generate_review_outputs.py.

Each packet mirrors the style of the original 5-example pilot packet
(npj-perspective-2026/visit_prep_review_packet.md) — patient record, then
AI-generated output, per example — but with the updated rubric:
- Accuracy rated per category present in the output (plus a Context
  Summary row), 4-way (Fully Supported / Partially Supported / Unsupported
  / N/A), instead of the original single free-text claim list.
- Relevance / Clarity / Usefulness rated once per example, 3-way, instead
  of the original 1-5 scale.
- A "missing category?" completeness question added, once per example.
- Would-you-bring-this-to-an-appointment (Yes/No) and free-text notes,
  once per example, as before.

Round 1 -> examples 1-10, round 2 -> 11-20, round 3 -> 21-30, matching how
the 3 reviewer groups are being labeled.

Requires `pandoc` (with a PDF engine, e.g. xelatex) on PATH to render the
.pdf; the .md is always written regardless.

Usage:
    python -m eval.build_review_packets [--in PATH] [--out-dir DIR]
"""

import argparse
import json
import subprocess
from datetime import datetime
from pathlib import Path

from eval.fixtures import GENERATION_CASES, EvalCase
from eval.fixtures_review_study import REVIEW_STUDY_CASES

RESULTS_DIR = Path(__file__).parent / "results"

KNOWN_CATEGORIES = [
    "Condition Management", "Medication Review", "Lab Results & Monitoring",
    "Lifestyle & Prevention", "Follow-up Planning",
]

ACCURACY_DEF = (
    "**Fully Supported** — every factual claim in this category (or the context summary) is "
    "stated in, or reasonably inferable from, the patient record. **Partially Supported** — at "
    "least one claim is unsupported, but not all. **Unsupported** — most/all claims are "
    "unsupported, OR any single claim would materially mislead the patient (e.g. a named "
    "external authority/guideline, or a specialty-management claim, not stated in the record). "
    "**N/A** — this category has no factual claims to check (purely open-ended/logistical questions)."
)


def _fmt_date(iso: str) -> str:
    dt = datetime.fromisoformat(iso)
    return dt.strftime("%b %-d %Y, %-I:%M %p")


def format_patient_record(case: EvalCase) -> list[str]:
    doctors_by_key = {d.key: d for d in case.doctors}
    target = doctors_by_key[case.target_doctor_key]
    lines = []
    clinic = f", {target.clinic}" if target.clinic else ""
    lines.append(
        f"- **Upcoming appointment:** {case.appointment_purpose}, "
        f"{_fmt_date(case.appointment_scheduled_date)}, with {target.name} "
        f"({target.specialty or 'Unknown specialty'}{clinic})"
    )

    if case.conditions:
        parts = []
        for c in case.conditions:
            scope_note = "" if c.in_scope else ", unrelated to today's visit"
            sev = f", {c.severity}" if c.severity else ""
            parts.append(f"{c.name} ({c.status}{sev}{scope_note})")
        lines.append(f"- **Conditions:** {'; '.join(parts)}")
    else:
        lines.append("- **Conditions:** none on file")

    if case.medications:
        parts = []
        for m in case.medications:
            presc = doctors_by_key.get(m.prescribing_doctor_key)
            presc_txt = f" (prescribed by {presc.name}" if presc else " (prescriber unknown"
            if presc and presc.specialty:
                presc_txt += f", {presc.specialty}"
            if presc and presc.clinic:
                presc_txt += f", {presc.clinic}"
            purpose_txt = f", for {m.purpose}" if m.purpose else ""
            presc_txt += f"{purpose_txt})"
            freq = f" {m.frequency}" if m.frequency else ""
            parts.append(f"{m.name} {m.dosage or ''}{freq}{presc_txt}".replace("  ", " "))
        lines.append(f"- **Medications:** {'; '.join(parts)}")
    else:
        lines.append("- **Medications:** none on file")

    if case.lab_orders:
        parts = [f"{l.test_name}, ordered {l.ordered_date}" for l in case.lab_orders]
        lines.append(f"- **Lab orders:** {'; '.join(parts)}")
    else:
        lines.append("- **Lab orders:** none on file")

    if case.vitals:
        parts = []
        for v in case.vitals:
            bits = [x for x in [v.weight, f"BMI {v.bmi}" if v.bmi else None, v.blood_pressure] if x]
            parts.append(f"{', '.join(bits)}, measured {v.measured_date}")
        lines.append(f"- **Vitals:** {'; '.join(parts)}")
    else:
        lines.append("- **Vitals:** none on file")

    if case.past_visits:
        lines.append("- **Past visits:**")
        for pv in sorted(case.past_visits, key=lambda p: p.scheduled_date, reverse=True):
            doc_name = doctors_by_key[pv.doctor_key].name
            lines.append(f"    - {_fmt_date(pv.scheduled_date)} — {pv.purpose or ''} "
                         f"(with {doc_name}). Notes: \"{pv.visit_notes or ''}\"")
    else:
        lines.append("- **Past visits:** none on file")

    return lines


def format_ai_output(raw_result: dict) -> list[str]:
    lines = []
    questions = raw_result.get("questions") or {}
    for category in KNOWN_CATEGORIES:
        qs = questions.get(category)
        if not qs:
            continue
        lines.append(f"**{category}**")
        lines.append("")
        for q in qs:
            lines.append(f"- {q}")
        lines.append("")
    summary = raw_result.get("context_summary")
    if summary:
        lines.append(f"**Context summary shown to patient:** \"{summary}\"")
    else:
        lines.append("**Context summary shown to patient:** (none generated for this example)")
    return lines


def categories_present(raw_result: dict) -> list[str]:
    questions = raw_result.get("questions") or {}
    return [c for c in KNOWN_CATEGORIES if questions.get(c)]


def build_example_section(example_number: int, case: EvalCase, raw_result: dict) -> list[str]:
    lines = [f"## Example {example_number}: {case.id}", "", f"*{case.description}*", ""]
    lines.append("**Patient record:**")
    lines.append("")
    lines.extend(format_patient_record(case))
    lines.append("")
    lines.append("**AI-generated output:**")
    lines.append("")
    lines.extend(format_ai_output(raw_result))
    lines.append("")

    cats = categories_present(raw_result) + ["Context Summary"]
    lines.append("**Your ratings for this example:**")
    lines.append("")
    lines.append("*Accuracy — rate EACH row below against the patient record above:*")
    lines.append("")
    for c in cats:
        lines.append(f"- {c}: Fully Supported / Partially Supported / Unsupported / N/A — _______")
    lines.append("")
    lines.append(
        "- **Relevance** (are the questions relevant to this patient's actual conditions, "
        "medications, and appointment purpose?): Relevant / Partially Relevant / Not Relevant — _______"
    )
    lines.append(
        "- **Clarity** (are the questions clearly phrased and understandable to a patient, not "
        "overly clinical or confusing?): Clear / Partially Clear / Confusing — _______"
    )
    lines.append(
        "- **Usefulness** (would bringing these questions to the appointment genuinely help the "
        "conversation with the doctor?): Useful / Partially Useful / Not Useful — _______"
    )
    lines.append(
        "- **Missing category?** (given the patient record above, is there a category you'd "
        "expect to see that's missing entirely from the output?): None missing / "
        + " / ".join(KNOWN_CATEGORIES) + " / Other (note below) — _______"
    )
    lines.append("- **Would you personally bring this to an appointment, if it were your own visit?** Yes / No / Not sure — _______")
    lines.append("- **Notes** (anything confusing, redundant, or that stood out, positively or negatively?): _______")
    lines.append("")
    lines.append("---")
    lines.append("")
    return lines


def build_packet_md(examples: list[dict], cases_by_id: dict[str, EvalCase], round_label: str, range_label: str) -> str:
    lines = [
        f"# HealthSteward Visit-Prep Review Packet — {round_label}",
        "",
        "Thank you for taking about 30 minutes to review this. This is for a research paper "
        "evaluating an AI health-coordination tool called HealthSteward. All patient details "
        "below are **synthetic/fictional test data** — no real patient information is involved.",
        "",
        "## What you're reviewing",
        "",
        "HealthSteward generates \"visit preparation\" — a set of categorized questions and a "
        "short context summary — meant to help a patient prepare for an upcoming doctor's "
        f"appointment, based on their medical history. Below are {range_label} (10 examples), "
        "drawn from a stratified 30-case set spanning routine and adversarial patient scenarios "
        "across many specialties. Each includes a **full patient record** (exactly what the AI "
        "system had access to), then the AI-generated output, then a set of ratings to fill in.",
        "",
        "For **Accuracy**, use the patient record as your ground truth: rate each category "
        "(and the context summary) separately. " + ACCURACY_DEF,
        "",
        "---",
        "",
    ]
    for ex in examples:
        case = cases_by_id[ex["case_id"]]
        lines.extend(build_example_section(ex["example_number"], case, ex["raw_result"]))

    lines.append(
        "## Overall (after all 10 examples)"
    )
    lines.append("")
    lines.append(
        "Any general impressions of the tool's usefulness for patients navigating fragmented "
        "care across multiple specialists — including those managing multiple chronic "
        "conditions or systemic immune and hormonal comorbidities?"
    )
    lines.append("")
    lines.append("_______________________________________________")
    lines.append("")
    lines.append("Thank you — this feedback goes directly into a research paper's evaluation section.")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--in", dest="in_path", type=Path, default=RESULTS_DIR / "review_study_outputs.json")
    parser.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = parser.parse_args()

    data = json.loads(args.in_path.read_text())
    examples = data["examples"]
    assert len(examples) == 30

    cases_by_id = {c.id: c for c in GENERATION_CASES + REVIEW_STUDY_CASES}

    groups = [
        ("round1_examples_1-10", "Round 1 — Examples 1-10", "Examples 1-10", examples[0:10]),
        ("round2_examples_11-20", "Round 2 — Examples 11-20", "Examples 11-20", examples[10:20]),
        ("round3_examples_21-30", "Round 3 — Examples 21-30", "Examples 21-30", examples[20:30]),
    ]
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for slug, round_label, range_label, group in groups:
        md_content = build_packet_md(group, cases_by_id, round_label, range_label)
        md_path = args.out_dir / f"HS-review-packet-{slug}.md"
        md_path.write_text(md_content)
        print(f"Wrote {md_path}")

        pdf_path = args.out_dir / f"HS-review-packet-{slug}.pdf"
        result = subprocess.run(
            ["pandoc", str(md_path), "-o", str(pdf_path), "--pdf-engine=xelatex", "-V", "geometry:margin=1in"],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            print(f"  pandoc FAILED for {slug}: {result.stderr[-2000:]}")
        else:
            print(f"Wrote {pdf_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
