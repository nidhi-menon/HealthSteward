"""Judge-noise-isolation check for the 30-case review study's pre-fix vs.
post-fix (output_guardrails.py regex fix) claim-level unsupported rate —
same method as eval/judge_noise_check.py (re-judge the SAME already-
generated, fixed output multiple times per version, to separate a real
prompt/code effect from the judge's own non-pinnable-temperature noise),
adapted to this study's 30-case pool and its own results file format
(eval/generate_review_outputs.py's {"examples": [...]}, not eval/run.py's
{"cases": [...]}).

Usage:
    python -m eval.judge_noise_check_review_study [--repeats N]

Reads eval/results/review_study_outputs_prefix_backup.json (pre-fix) and
eval/results/review_study_outputs_postfix.json (post-fix) — both already
generated, never re-generated by this script.
"""

import argparse
import asyncio
import json
import sys
from pathlib import Path

from eval.fixtures import GENERATION_CASES
from eval.fixtures_review_study import REVIEW_STUDY_CASES
from eval.judge import score_factual_groundedness
from src.agents.llm_backend import ClaudeBackend
from src.config import get_settings

RESULTS_DIR = Path(__file__).parent / "results"
CASES_BY_ID = {c.id: c for c in GENERATION_CASES + REVIEW_STUDY_CASES}


def _load_cases_and_results(path: Path) -> list[tuple]:
    data = json.loads(path.read_text())
    return [(CASES_BY_ID[ex["case_id"]], ex["raw_result"]) for ex in data["examples"]]


async def _judge_pass(cases_and_results: list[tuple], judge_backend: ClaudeBackend) -> dict:
    all_claims = []
    skipped = []
    for case, raw_result in cases_and_results:
        # score_factual_groundedness already retries 3x internally on a
        # malformed/empty response; a case that still fails after that is a
        # real, if rare, judge failure mode (observed in practice at this
        # scale — 30 cases/pass x 3 passes x 2 versions = 180 calls, high
        # enough volume that the original 5-case judge_noise_check.py's
        # no-catch posture (fine at n=25) isn't safe here). Skipped from
        # this pass's rate rather than aborting the whole ~60-90min run —
        # recorded, not silently dropped, so a skew from missing claims is
        # visible in the output, not hidden.
        try:
            report = await score_factual_groundedness(case, raw_result, judge_backend)
            all_claims.extend(report["claims"])
        except ValueError as e:
            print(f"    [SKIPPED] {case.id}: {e}"[:200])
            skipped.append(case.id)

    scored = [c for c in all_claims if c.get("verdict") in ("grounded", "unsupported")]
    unsupported = [c for c in scored if c["verdict"] == "unsupported"]
    return {
        "unsupported_rate": (len(unsupported) / len(scored)) if scored else None,
        "scored_claims": len(scored),
        "unsupported_claims": len(unsupported),
        "skipped_cases": skipped,
    }


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prefix", type=Path, default=RESULTS_DIR / "review_study_outputs_prefix_backup.json")
    parser.add_argument("--postfix", type=Path, default=RESULTS_DIR / "review_study_outputs_postfix.json")
    # 3, not the original script's 5 — 30 cases/pass makes 5 repeats ~150
    # judge calls per version (~300 total, ~90-100 min at this judge's
    # observed per-call latency); 3 repeats still gives a real noise range
    # (min/max/mean) per version at roughly half the wall-clock, a
    # deliberate cost/deadline tradeoff over the original script's default.
    parser.add_argument("--repeats", type=int, default=3)
    args = parser.parse_args()

    settings = get_settings()
    if not settings.anthropic_api_key:
        print("ERROR: ANTHROPIC_API_KEY not set.", file=sys.stderr)
        return 1
    judge_backend = ClaudeBackend(settings, model=settings.anthropic_judge_model)

    prefix_cases = _load_cases_and_results(args.prefix)
    postfix_cases = _load_cases_and_results(args.postfix)
    assert len(prefix_cases) == 30 and len(postfix_cases) == 30

    results = {"prefix": [], "postfix": []}
    for label, cases_and_results in [("prefix", prefix_cases), ("postfix", postfix_cases)]:
        print(f"=== Re-judging '{label}' output {args.repeats}x (judge: {settings.anthropic_judge_model}) ===")
        for i in range(args.repeats):
            pass_result = await _judge_pass(cases_and_results, judge_backend)
            print(f"  pass {i + 1}/{args.repeats}: unsupported_rate={pass_result['unsupported_rate']} "
                  f"({pass_result['unsupported_claims']}/{pass_result['scored_claims']})")
            results[label].append(pass_result)

    print("\n=== Summary ===")
    for label in ("prefix", "postfix"):
        rates = [r["unsupported_rate"] for r in results[label] if r["unsupported_rate"] is not None]
        print(f"{label}: rates={rates}")
        if rates:
            print(f"  min={min(rates):.3f} max={max(rates):.3f} mean={sum(rates) / len(rates):.3f} "
                  f"range={max(rates) - min(rates):.3f}")

    out_path = RESULTS_DIR / "judge_noise_check_review_study.json"
    out_path.write_text(json.dumps(results, indent=2))
    print(f"\nWrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
