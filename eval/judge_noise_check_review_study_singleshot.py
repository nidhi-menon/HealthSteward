"""Judge-noise-isolation check for the 30-case review study's single-shot
outputs — same method as eval/judge_noise_check_review_study.py (re-judge
the SAME already-generated output multiple times, to separate a real
prompt/code effect from the judge's own non-pinnable-temperature noise),
pointed at the single-shot results file instead of the agentic pre/post-fix
files.

Usage:
    python -m eval.judge_noise_check_review_study_singleshot [--repeats N]

Reads eval/results/review_study_outputs_singleshot.json (already
generated, AGENT_TOOL_USE_ENABLED=false, never re-generated by this
script). The existing eval/results/judge_review_study_results_singleshot.json
single-pass run (8.20%, 21/256) counts as pass 1 of this noise check; this
script produces 2 additional passes so the single-shot side has a 3-pass
range/mean directly comparable to the agentic postfix noise check.
"""

import argparse
import asyncio
import json
import sys
from pathlib import Path

from eval.fixtures import GENERATION_CASES
from eval.fixtures_review_study import REVIEW_STUDY_CASES
from eval.judge import score_factual_groundedness
from src.agents.llm_backend import ClaudeBackend
from src.config import get_settings

RESULTS_DIR = Path(__file__).parent / "results"
CASES_BY_ID = {c.id: c for c in GENERATION_CASES + REVIEW_STUDY_CASES}


def _load_cases_and_results(path: Path) -> list[tuple]:
    data = json.loads(path.read_text())
    return [(CASES_BY_ID[ex["case_id"]], ex["raw_result"]) for ex in data["examples"]]


async def _judge_pass(cases_and_results: list[tuple], judge_backend: ClaudeBackend) -> dict:
    all_claims = []
    skipped = []
    for case, raw_result in cases_and_results:
        # Same bounded-skip posture as judge_noise_check_review_study.py:
        # score_factual_groundedness already retries 3x internally, a case
        # that still fails is skipped from this pass's rate (recorded, not
        # silently dropped) rather than aborting the whole run.
        try:
            report = await score_factual_groundedness(case, raw_result, judge_backend)
            all_claims.extend(report["claims"])
        except ValueError as e:
            print(f"    [SKIPPED] {case.id}: {e}"[:200])
            skipped.append(case.id)

    scored = [c for c in all_claims if c.get("verdict") in ("grounded", "unsupported")]
    unsupported = [c for c in scored if c["verdict"] == "unsupported"]
    return {
        "unsupported_rate": (len(unsupported) / len(scored)) if scored else None,
        "scored_claims": len(scored),
        "unsupported_claims": len(unsupported),
        "skipped_cases": skipped,
    }


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--singleshot", type=Path, default=RESULTS_DIR / "review_study_outputs_singleshot.json")
    # 2, not 3 — the existing single-pass judge_review_study_results_singleshot.json
    # run (8.20%, 21/256) already counts as pass 1; this script only needs
    # to produce 2 more passes to get a 3-pass range/mean.
    parser.add_argument("--repeats", type=int, default=2)
    args = parser.parse_args()

    settings = get_settings()
    if not settings.anthropic_api_key:
        print("ERROR: ANTHROPIC_API_KEY not set.", file=sys.stderr)
        return 1
    judge_backend = ClaudeBackend(settings, model=settings.anthropic_judge_model)

    singleshot_cases = _load_cases_and_results(args.singleshot)
    assert len(singleshot_cases) == 30

    results = {"singleshot": []}
    print(f"=== Re-judging 'singleshot' output {args.repeats}x (judge: {settings.anthropic_judge_model}) ===")
    for i in range(args.repeats):
        pass_result = await _judge_pass(singleshot_cases, judge_backend)
        print(f"  pass {i + 1}/{args.repeats}: unsupported_rate={pass_result['unsupported_rate']} "
              f"({pass_result['unsupported_claims']}/{pass_result['scored_claims']})")
        results["singleshot"].append(pass_result)

    print("\n=== Summary ===")
    rates = [r["unsupported_rate"] for r in results["singleshot"] if r["unsupported_rate"] is not None]
    print(f"singleshot (2 new passes): rates={rates}")
    if rates:
        print(f"  min={min(rates):.3f} max={max(rates):.3f} mean={sum(rates) / len(rates):.3f} "
              f"range={max(rates) - min(rates):.3f}")

    out_path = RESULTS_DIR / "judge_noise_check_review_study_singleshot.json"
    out_path.write_text(json.dumps(results, indent=2))
    print(f"\nWrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
